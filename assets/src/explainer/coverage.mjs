// Explainer visual, drawn from real runs: where BFS and Go-Explore spend the same 200,000-step budget on
// the dungeon example's `#deep` level, and the witness path Go-Explore returns.
//
//   node assets/src/explainer/coverage.mjs      -> assets/explore-coverage-{light,dark}.svg
import { writeFileSync } from 'node:fs';
import { inProcessDriver, explore, replay } from '../../../src/index.mjs';
import { deep } from '../../../examples/dungeon/target.mjs';
import { LEVELS } from '../../../examples/dungeon/game.mjs';

const BUDGET = 200000;
const map = LEVELS.catacombs.map;
const W = map[0].length, H = map.length;

/** Explore with a driver whose visit() counts distinct states per player tile. */
async function coverage(strategy) {
  const d = inProcessDriver(deep);
  const counts = new Map(), seen = new Set();
  const visit = d.visit.bind(d);
  d.visit = async (s) => {
    const info = await visit(s);
    if (!seen.has(info.hash)) {
      seen.add(info.hash);
      const k = `${s.player.x},${s.player.y}`;
      counts.set(k, (counts.get(k) ?? 0) + 1);
    }
    return info;
  };
  const r = await explore(d, { strategy, maxSteps: BUDGET, seed: 1, verify: false });
  let path = [];
  const v = r.violations[0];
  if (v) {
    const p = inProcessDriver(deep);
    const tiles = [];
    const pv = p.visit.bind(p);
    p.visit = async (s) => { tiles.push([s.player.x, s.player.y]); return pv(s); };
    await replay(p, v.trace, { actionLabels: false });
    path = tiles;
  }
  return { counts, r, path };
}

const THEMES = {
  light: { bg: '#ffffff', wall: '#d0d7de', floor: '#f6f8fa', ink: '#1f2328', dim: '#59636e', heat: '31,35,40', path: '#c0392b', door: '#8c959f' },
  dark: { bg: '#0d1117', wall: '#30363d', floor: '#161b22', ink: '#e6edf3', dim: '#9198a1', heat: '230,237,243', path: '#ff7b72', door: '#6e7681' },
};
const CELL = 22, PAD = 24, GAP = 40, TOP = 92;

function panel(t, ox, title, sub, { counts, path }, max) {
  const out = [];
  out.push(`<text x="${ox}" y="${TOP - 34}" class="h">${title}</text>`, `<text x="${ox}" y="${TOP - 14}" class="s">${sub}</text>`);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    const ch = map[y][x], X = ox + x * CELL, Y = TOP + y * CELL;
    if (ch === '#') { out.push(`<rect x="${X}" y="${Y}" width="${CELL}" height="${CELL}" fill="${t.wall}"/>`); continue; }
    out.push(`<rect x="${X}" y="${Y}" width="${CELL}" height="${CELL}" fill="${t.floor}"/>`);
    const n = counts.get(`${x},${y}`) ?? 0;
    if (n) out.push(`<rect x="${X + 1}" y="${Y + 1}" width="${CELL - 2}" height="${CELL - 2}" rx="2" fill="rgba(${t.heat},${(0.12 + 0.78 * Math.log1p(n) / Math.log1p(max)).toFixed(3)})"/>`);
    if (ch === '~') out.push(`<text x="${X + CELL / 2}" y="${Y + 15}" class="g" fill="${t.dim}">~</text>`);
    if ('DEk'.includes(ch)) out.push(`<text x="${X + CELL / 2}" y="${Y + 15}" class="g" fill="${ch === 'k' ? t.path : t.door}" font-weight="700">${ch === 'k' ? 'k' : ch}</text>`);
  }
  if (path.length) {
    const pts = path.map(([x, y]) => `${ox + x * CELL + CELL / 2},${TOP + y * CELL + CELL / 2}`).join(' ');
    out.push(`<polyline points="${pts}" fill="none" stroke="${t.path}" stroke-width="2.5" stroke-linejoin="round" stroke-linecap="round"/>`);
    const [ex, ey] = path[path.length - 1];
    out.push(`<circle cx="${ox + ex * CELL + CELL / 2}" cy="${TOP + ey * CELL + CELL / 2}" r="8" fill="none" stroke="${t.path}" stroke-width="2"/>`);
  }
  return out.join('\n  ');
}

const bfs = await coverage('bfs');
const go = await coverage('go-explore');
const max = Math.max(...bfs.counts.values(), ...go.counts.values());
const panelW = W * CELL, width = PAD * 2 + panelW * 2 + GAP, height = TOP + H * CELL + 64;
const fmt = (n) => n.toLocaleString('en-US');
for (const [name, t] of Object.entries(THEMES)) {
  const v = go.r.violations[0];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" font-family="ui-sans-serif, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif">
  <!-- Generated by assets/src/explainer/coverage.mjs from real runs of examples/dungeon/target.mjs#deep. -->
  <style>.h{font-size:16px;font-weight:600;fill:${t.ink}}.s{font-size:13px;fill:${t.dim}}.g{font-size:14px;text-anchor:middle;font-family:ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}.f{font-size:13px;fill:${t.dim}}</style>
  <rect width="100%" height="100%" fill="${t.bg}" rx="8"/>
  ${panel(t, PAD, 'BFS: 200,000 steps', `${fmt(bfs.r.stats.states)} states, all within ${bfs.r.stats.depth} moves of the start. Bug not found.`, bfs, max)}
  ${panel(t, PAD + panelW + GAP, 'Go-Explore: the same 200,000 steps', `${fmt(go.r.stats.states)} states in ${go.r.stats.cells} cells. Softlock found: a ${v.length}-move witness.`, go, max)}
  <text x="${PAD}" y="${height - 22}" class="f">Shading: distinct states explored with the player on that tile (log scale). k = key, D = locked door, E = exit. Red: the witness, shrunk to 1-minimal.</text>
</svg>
`;
  writeFileSync(new URL(`../../explore-coverage-${name}.svg`, import.meta.url), svg);
}
console.log(`bfs: ${bfs.r.stats.states} states, depth ${bfs.r.stats.depth}, violations ${bfs.r.violations.length}`);
console.log(`go-explore: ${go.r.stats.states} states, ${go.r.stats.cells} cells, witness ${go.r.violations[0]?.length}`);
